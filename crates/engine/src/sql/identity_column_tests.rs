/// COPY は PostgreSQL と同じく IDENTITY 列へ入力値をそのまま書く（ALWAYS でも `428C9` にしない）。
/// IDENTITY 列を省略した COPY は既存の「COPY では採番しない」に従い `0A000`。
#[test]
fn copy_writes_identity_values_but_does_not_number_omitted_columns() {
    let (_p, _g, core) = fixture("identity-copy");
    ok(
        &core,
        "sys",
        "CREATE TABLE t (id BIGINT PRIMARY KEY, n INTEGER GENERATED ALWAYS AS IDENTITY, v TEXT)",
    );
    let run_copy = |sql: &str, data: &[u8]| {
        let session = SessionState::default();
        let plan = core.begin_copy(&ctx("alice"), &session, sql)?;
        let mut copy = match plan {
            crate::core::CopyPlan::From(s) => s,
            crate::core::CopyPlan::To(..) => panic!("expected COPY FROM STDIN plan"),
        };
        copy.feed(data)?;
        let batch = copy.finish()?;
        core.commit_copy_in(&ctx("alice"), batch)
    };
    run_copy(
        "COPY t (id, n, v) FROM STDIN USING OPERATION_ID 'c1'",
        b"1\t42\tx\n",
    )
    .expect("copy with explicit identity value");
    assert_eq!(column_n(&core, "alice"), vec![42]);
    let omitted = run_copy(
        "COPY t (id, v) FROM STDIN USING OPERATION_ID 'c2'",
        b"2\tx\n",
    );
    let err = omitted.expect_err("omitted identity column must not be numbered by COPY");
    assert_eq!(err.wire_code(), "0A000");
}

/// 自動更新可能ビュー経由の書き込みも、基表へ書き換えた後に同じ束縛を通るため、ALWAYS 列への
/// 明示値・UPDATE の SET は `428C9`（ビューが迂回路にならない）。省略した INSERT は採番する。
#[test]
fn view_writes_cannot_bypass_generated_always() {
    let (_p, _g, core) = fixture("identity-view");
    ok(
        &core,
        "sys",
        "CREATE TABLE t (id BIGINT PRIMARY KEY, n INTEGER GENERATED ALWAYS AS IDENTITY, v TEXT)",
    );
    ok(&core, "sys", "CREATE VIEW vw AS SELECT id, n, v FROM t");
    assert_eq!(
        code(
            &core,
            "alice",
            "INSERT INTO vw (id, n, v) VALUES (1, 5, 'x') USING OPERATION_ID 'v1'"
        ),
        "428C9"
    );
    ok(
        &core,
        "alice",
        "INSERT INTO vw (id, v) VALUES (1, 'x') USING OPERATION_ID 'v2'",
    );
    assert_eq!(column_n(&core, "alice"), vec![1]);
    assert_eq!(
        code(
            &core,
            "alice",
            "UPDATE vw SET n = 9 WHERE id = 1 USING OPERATION_ID 'v3'"
        ),
        "428C9"
    );
}
