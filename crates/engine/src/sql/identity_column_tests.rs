/// ライフサイクル: DROP SEQUENCE の 2BP01、RENAME の追従、DROP TABLE での連動削除、RESTART IDENTITY。
#[test]
fn identity_sequence_lifecycle_follows_owner() {
    let (_p, _g, core) = fixture("identity-lifecycle");
    ok(
        &core,
        "sys",
        "CREATE TABLE t (id BIGINT PRIMARY KEY, n INTEGER GENERATED BY DEFAULT AS IDENTITY (START 5), v TEXT)",
    );
    assert_eq!(code(&core, "sys", "DROP SEQUENCE t_n_seq"), "2BP01");
    assert_eq!(
        code(&core, "sys", "ALTER SEQUENCE t_n_seq RENAME TO x"),
        "0A000"
    );
    insert_t(&core, "alice", 1, "a1");
    insert_t(&core, "alice", 2, "a2");
    assert_eq!(column_n(&core, "alice"), vec![5, 6]);
    ok(&core, "alice", "TRUNCATE t RESTART IDENTITY");
    insert_t(&core, "alice", 3, "a3");
    assert_eq!(column_n(&core, "alice"), vec![5]);

    ok(&core, "sys", "ALTER TABLE t RENAME TO t2");
    let storage = core.storage_for_test();
    let owner = storage.sequence_owner("t_n_seq").expect("o").expect("some");
    assert_eq!(owner.table, "t2");
    ok(&core, "sys", "DROP TABLE t2");
    assert_eq!(code(&core, "sys", "DROP SEQUENCE t_n_seq"), "42P01");

    ok(
        &core,
        "sys",
        "CREATE TABLE c (id BIGINT PRIMARY KEY, n INTEGER GENERATED ALWAYS AS IDENTITY, w TEXT)",
    );
    ok(&core, "sys", "ALTER TABLE c DROP COLUMN n");
    assert_eq!(code(&core, "sys", "DROP SEQUENCE c_n_seq"), "42P01");
}

