//! `GENERATED { ALWAYS | BY DEFAULT } AS IDENTITY` 列（TABLE-24・Issue #1695）の crate 内結合テスト。
//! ポインタ: `docs/spec/04-behavior/data-model.md` TABLE-24（拒否の分類は ERR-6 の `428C9`）。
//! 設計記録は `docs/design/sequence-namespace-and-ledger.md`「Issue #1695 実装記録」。
//!
//! 所有者（`SequenceOwner`）・列の `DEFAULT` 表現はカタログ内部の宣言のため、`Storage` の内部 API で
//! 読んで検証する。検証する契約:
//!
//! - `CREATE TABLE` の IDENTITY 列は整数型・`NOT NULL`・`ColumnDefault::Identity` と、その列が所有する
//!   暗黙 SEQUENCE へ展開され、再オープン後も往復で保たれる
//! - ALWAYS 列への明示値・明示 NULL・UPDATE の SET は `428C9`（型の束縛より前・SEQUENCE を進めない）。
//!   BY DEFAULT は明示値を受け付ける。COPY は PostgreSQL と同じく IDENTITY 列へ入力値をそのまま書く
//! - 未対応の形（`OVERRIDING`・ALTER の IDENTITY 操作・型変更・一時表・生成列など）は fail-closed

use crate::catalog::{ColumnDefault, ColumnType, IdentityKind};
use crate::core::EngineCore;
use crate::kernel::CpuScalarProvider;
use crate::policy::PolicyContext;
use crate::sql::allowlist::SqlSurfaceError;
use crate::sql::exec::Cell;
use crate::sql::mode::SessionState;
use crate::sql::SqlOutcome;
use crate::storage::{Storage, Visibility};
use crate::test_util::temp_db::{unique_db_path, CleanupGuard};

fn ctx(tenant: &str) -> PolicyContext {
    PolicyContext::with_visibilities(tenant, [Visibility::Public, Visibility::Private])
        .expect("valid tenant")
}

fn open_core(path: &std::path::Path) -> EngineCore {
    EngineCore::from_storage(
        Storage::open(path).expect("open storage"),
        Box::new(CpuScalarProvider),
    )
}

fn run(core: &EngineCore, tenant: &str, sql: &str) -> Result<SqlOutcome, SqlSurfaceError> {
    let mut session = SessionState::default();
    session.allow_ddl();
    core.execute_sql_in_session(&ctx(tenant), &mut session, sql)
}

fn ok(core: &EngineCore, tenant: &str, sql: &str) {
    run(core, tenant, sql).unwrap_or_else(|e| panic!("{sql} must succeed: {e}"));
}

fn code(core: &EngineCore, tenant: &str, sql: &str) -> &'static str {
    match run(core, tenant, sql) {
        Ok(o) => panic!("{sql} must fail, got {o:?}"),
        Err(e) => e.wire_code(),
    }
}

fn fixture(label: &str) -> (std::path::PathBuf, CleanupGuard, EngineCore) {
    let path = unique_db_path(label);
    let guard = CleanupGuard(path.clone());
    let core = open_core(&path);
    (path, guard, core)
}

/// `t` に 1 行入れる（`n` を省略して採番させる）。
fn insert_t(core: &EngineCore, tenant: &str, id: u64, op: &str) {
    ok(
        core,
        tenant,
        &format!("INSERT INTO t (id, v) VALUES ({id}, 'x') USING OPERATION_ID '{op}'"),
    );
}

/// `t.n` を id 昇順で返す。
fn column_n(core: &EngineCore, tenant: &str) -> Vec<i64> {
    let r = core
        .execute_sql(&ctx(tenant), "SELECT id, n FROM t LIMIT 1000")
        .expect("select");
    let mut rows: Vec<(u64, i64)> = r
        .rows
        .iter()
        .map(|row| {
            // 宣言した `id BIGINT` 列（TABLE-23・Issue #2199 以降の表は暗黙の `id` を持たない）。
            let id = match row.cells[0] {
                Cell::SignedInteger(v) => u64::try_from(v).expect("non-negative id"),
                ref o => panic!("id cell {o:?}"),
            };
            let n = match row.cells[1] {
                Cell::SignedInteger(v) => v,
                ref o => panic!("n cell {o:?}"),
            };
            (id, n)
        })
        .collect();
    rows.sort();
    rows.into_iter().map(|(_, n)| n).collect()
}

/// 受け入れ条件 1: 展開結果（型・NOT NULL・DEFAULT 表現・所有者・既定パラメータ）と再オープン後の往復。
#[test]
fn identity_expands_and_survives_reopen() {
    let (path, _g, core) = fixture("identity-basic");
    ok(
        &core,
        "sys",
        "CREATE TABLE t (id BIGINT PRIMARY KEY, n INTEGER GENERATED ALWAYS AS IDENTITY, v TEXT)",
    );
    ok(
        &core,
        "sys",
        "CREATE TABLE u (id BIGINT PRIMARY KEY, n bigint generated by default as identity, v TEXT)",
    );
    let storage = core.storage_for_test();
    let schema = storage.get_table_schema("t").expect("schema");
    let col = schema.columns.iter().find(|c| c.name == "n").expect("n");
    assert_eq!(col.ty, ColumnType::Integer);
    assert!(!col.nullable);
    assert_eq!(
        col.default_expr,
        Some(ColumnDefault::Identity {
            sequence: "t_n_seq".to_string(),
            kind: IdentityKind::Always
        })
    );
    let owner = storage
        .sequence_owner("t_n_seq")
        .expect("owner")
        .expect("some");
    assert_eq!((owner.table.as_str(), owner.column.as_str()), ("t", "n"));
    let def = storage
        .sequence_definition_full("t_n_seq")
        .expect("def")
        .expect("exists");
    assert_eq!(def.params.increment, 1);
    assert_eq!(def.params.min_value, 1);
    assert_eq!(def.params.start, 1);
    assert_eq!(def.params.max_value, i64::from(i32::MAX));
    assert!(!def.params.cycle);
    let u = storage.get_table_schema("u").expect("schema");
    assert_eq!(
        u.columns[1].default_expr,
        Some(ColumnDefault::Identity {
            sequence: "u_n_seq".to_string(),
            kind: IdentityKind::ByDefault
        })
    );

    insert_t(&core, "alice", 1, "a1");
    insert_t(&core, "alice", 2, "a2");
    insert_t(&core, "bob", 1, "b1");
    assert_eq!(column_n(&core, "alice"), vec![1, 2]);
    assert_eq!(column_n(&core, "bob"), vec![1]);
    drop(core);
    let core = open_core(&path);
    let schema = core
        .storage_for_test()
        .get_table_schema("t")
        .expect("schema");
    assert_eq!(
        schema.columns[1].default_expr,
        Some(ColumnDefault::Identity {
            sequence: "t_n_seq".to_string(),
            kind: IdentityKind::Always
        })
    );
    insert_t(&core, "alice", 3, "a3");
    assert_eq!(column_n(&core, "alice"), vec![1, 2, 3]);
}

/// SEQUENCE オプション（START・INCREMENT・MIN/MAX・CYCLE・降順）の反映と列型の範囲検査。
#[test]
fn identity_sequence_options_are_applied_and_bounded_by_column_type() {
    let (_p, _g, core) = fixture("identity-options");
    ok(
        &core,
        "sys",
        "CREATE TABLE t (id BIGINT PRIMARY KEY, n SMALLINT GENERATED BY DEFAULT AS IDENTITY \
         (START WITH 10 INCREMENT BY 5 MINVALUE 10 MAXVALUE 100 CYCLE), v TEXT)",
    );
    let def = core
        .storage_for_test()
        .sequence_definition_full("t_n_seq")
        .expect("def")
        .expect("exists");
    assert_eq!(
        (
            def.params.start,
            def.params.increment,
            def.params.min_value,
            def.params.max_value,
            def.params.cycle
        ),
        (10, 5, 10, 100, true)
    );
    insert_t(&core, "alice", 1, "a1");
    insert_t(&core, "alice", 2, "a2");
    assert_eq!(column_n(&core, "alice"), vec![10, 15]);

    ok(
        &core,
        "sys",
        "CREATE TABLE d (id BIGINT PRIMARY KEY, n INTEGER GENERATED ALWAYS AS IDENTITY (INCREMENT -1), v TEXT)",
    );
    let def = core
        .storage_for_test()
        .sequence_definition_full("d_n_seq")
        .expect("def")
        .expect("exists");
    assert_eq!(def.params.max_value, -1);
    assert_eq!(def.params.start, -1);
    assert_eq!(def.params.min_value, i64::from(i32::MIN));

    for sql in [
        "CREATE TABLE r (id BIGINT PRIMARY KEY, n INTEGER GENERATED ALWAYS AS IDENTITY (MAXVALUE 2147483648))",
        "CREATE TABLE r (id BIGINT PRIMARY KEY, n SMALLINT GENERATED ALWAYS AS IDENTITY (START 40000))",
        "CREATE TABLE r (id BIGINT PRIMARY KEY, n INTEGER GENERATED ALWAYS AS IDENTITY (INCREMENT 0))",
        "CREATE TABLE r (id BIGINT PRIMARY KEY, n INTEGER GENERATED ALWAYS AS IDENTITY (MINVALUE 5 MAXVALUE 1))",
        "CREATE TABLE r (id BIGINT PRIMARY KEY, n TEXT GENERATED ALWAYS AS IDENTITY)",
        "CREATE TABLE r (id BIGINT PRIMARY KEY, n INTEGER[] GENERATED ALWAYS AS IDENTITY)",
        "CREATE TABLE r (id BIGINT PRIMARY KEY, n REAL GENERATED ALWAYS AS IDENTITY)",
    ] {
        assert_eq!(code(&core, "sys", sql), "22023", "{sql}");
    }
    assert_eq!(code(&core, "sys", "DROP SEQUENCE r_n_seq"), "42P01");
}

/// 受け入れ条件 2（ALWAYS）: 明示値・明示 NULL・複数行 VALUES の一部・UPSERT の挿入側は `428C9`。
/// 型不正な値でも 22P02 より先に `428C9` で、拒否された文は SEQUENCE を進めない。
#[test]
fn always_rejects_explicit_values_without_consuming_sequence() {
    let (_p, _g, core) = fixture("identity-always");
    ok(
        &core,
        "sys",
        "CREATE TABLE t (id BIGINT PRIMARY KEY, n INTEGER GENERATED ALWAYS AS IDENTITY, v TEXT)",
    );
    for sql in [
        "INSERT INTO t (id, n, v) VALUES (1, 5, 'x') USING OPERATION_ID 'r1'",
        "INSERT INTO t (id, n, v) VALUES (1, NULL, 'x') USING OPERATION_ID 'r2'",
        "INSERT INTO t (id, n, v) VALUES (1, 'not-a-number', 'x') USING OPERATION_ID 'r3'",
        "INSERT INTO t (id, v, n) VALUES (1, 'x', 5) USING OPERATION_ID 'r4'",
        "INSERT INTO t (id, v) VALUES (1, 'x'), (2, 'y') USING OPERATION_ID 'r5-ok'",
    ] {
        if sql.contains("r5-ok") {
            ok(&core, "alice", sql);
            continue;
        }
        assert_eq!(code(&core, "alice", sql), "428C9", "{sql}");
    }
    // 複数行 VALUES は全行が同じ列リストを共有するため、列に値を書く形は全て 428C9。
    assert_eq!(
        code(
            &core,
            "alice",
            "INSERT INTO t (id, n, v) VALUES (10, 1, 'x'), (11, 2, 'y') USING OPERATION_ID 'm1'"
        ),
        "428C9"
    );
    assert_eq!(
        code(
            &core,
            "alice",
            "INSERT INTO t (id, n, v) VALUES (12, 1, 'x') ON CONFLICT (id) DO NOTHING \
             USING OPERATION_ID 'm2'"
        ),
        "428C9"
    );
    // 拒否された文は採番しない: 直前の複数行 INSERT が 1・2 を使い、続きは 3。
    insert_t(&core, "alice", 3, "a3");
    assert_eq!(column_n(&core, "alice"), vec![1, 2, 3]);
}

/// UPDATE の SET（リテラル・式・述語形）と `DO UPDATE SET` も ALWAYS 列には書けない。BY DEFAULT は書ける。
#[test]
fn always_rejects_update_set_and_by_default_allows_it() {
    let (_p, _g, core) = fixture("identity-update");
    ok(
        &core,
        "sys",
        "CREATE TABLE t (id BIGINT PRIMARY KEY, n INTEGER GENERATED ALWAYS AS IDENTITY, v TEXT)",
    );
    ok(
        &core,
        "sys",
        "CREATE TABLE b (id BIGINT PRIMARY KEY, n INTEGER GENERATED BY DEFAULT AS IDENTITY, v TEXT)",
    );
    insert_t(&core, "alice", 1, "a1");
    for sql in [
        "UPDATE t SET n = 5 WHERE id = 1 USING OPERATION_ID 'u1'",
        "UPDATE t SET n = n + 1 WHERE id = 1 USING OPERATION_ID 'u2'",
        "UPDATE t SET n = 5 WHERE v = 'x' USING OPERATION_ID 'u3'",
    ] {
        assert_eq!(code(&core, "alice", sql), "428C9", "{sql}");
    }
    ok(
        &core,
        "alice",
        "UPDATE t SET v = 'y' WHERE id = 1 USING OPERATION_ID 'u5'",
    );
    assert_eq!(column_n(&core, "alice"), vec![1]);

    ok(
        &core,
        "alice",
        "INSERT INTO b (id, v) VALUES (1, 'x') USING OPERATION_ID 'b1'",
    );
    ok(
        &core,
        "alice",
        "UPDATE b SET n = 50 WHERE id = 1 USING OPERATION_ID 'b2'",
    );
}

