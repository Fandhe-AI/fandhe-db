//! 生成列（`GENERATED ALWAYS AS (<式>) STORED`）の宣言側の単体テスト（TABLE-50・Issue #3327）。
//! 構文段（`sql::allowlist` の列制約解析）と束縛段（`sql::generated_column::bind_generated_column`、
//! `sql::ddl::build_table_schema` 経由）の判定表を、SQLSTATE と正規描画で固定する。エンドツーエンドの
//! 結合（再起動・ダンプ往復・書き込み停止）は `tests/table_rls/table50_generated_column_create.rs`。

use crate::schema_limits::SchemaLimits;
use crate::sql::allowlist::{
    validate_create_table_tokens, validate_create_table_tokens_with_implicit_id,
    ValidatedCreateTable,
};
use crate::sql::lexer::tokenize;

fn parse(sql: &str) -> Result<ValidatedCreateTable, String> {
    let tokens = tokenize(sql).expect("tokenize");
    validate_create_table_tokens(&tokens).map_err(|e| e.wire_code().to_string())
}

fn parse_ok(sql: &str) -> ValidatedCreateTable {
    parse(sql).unwrap_or_else(|c| panic!("{sql} must parse, got {c}"))
}

/// 構文段 + 束縛段（カタログ非参照の `build_table_schema`）を通した結果の SQLSTATE。
fn build(sql: &str) -> Result<crate::catalog::TableSchema, String> {
    let validated = parse(sql)?;
    crate::sql::ddl::build_table_schema(None, &validated, &SchemaLimits::default())
        .map_err(|e| e.wire_code().to_string())
}

fn build_ok(sql: &str) -> crate::catalog::TableSchema {
    build(sql).unwrap_or_else(|c| panic!("{sql} must build, got {c}"))
}

#[test]
fn syntax_stage_collects_generated_columns_in_declaration_order() {
    let v = parse_ok(
        "CREATE TABLE t (a INTEGER, b INTEGER GENERATED ALWAYS AS (a * 2) STORED NOT NULL, \
         c TEXT, d TEXT GENERATED ALWAYS AS (lower(c)) STORED)",
    );
    let names: Vec<&str> = v
        .generated_columns
        .iter()
        .map(|g| g.column.as_str())
        .collect();
    assert_eq!(names, ["b", "d"]);
    let b = v.columns.iter().find(|c| c.name == "b").expect("b");
    assert!(!b.nullable);
    assert!(b.default_expr.is_none());
    assert!(
        !v.columns[0].is_generated(),
        "ColumnDef carries no expression before binding"
    );
}

#[test]
// intentional: docs/design/generated-column.md
fn syntax_stage_sqlstate_table() {
    for (sql, code) in [
        ("CREATE TABLE t (a INTEGER GENERATED ALWAYS AS (1) STORED GENERATED ALWAYS AS (2) STORED)", "42601"),
        ("CREATE TABLE t (a INTEGER GENERATED ALWAYS AS (1))", "42601"),
        ("CREATE TABLE t (a INTEGER GENERATED ALWAYS AS (1) VIRTUAL)", "42601"),
        ("CREATE TABLE t (a INTEGER GENERATED BY DEFAULT AS (1) STORED)", "42601"),
        ("CREATE TABLE t (a INTEGER GENERATED ALWAYS AS ()  STORED)", "42601"),
        ("CREATE TABLE t (a INTEGER GENERATED ALWAYS AS (1, 2) STORED)", "42601"),
        ("CREATE TABLE t (a INTEGER DEFAULT 1 GENERATED ALWAYS AS (1) STORED)", "42601"),
        ("CREATE TABLE t (a INTEGER GENERATED ALWAYS AS (1) STORED DEFAULT NULL)", "42601"),
        ("CREATE TABLE t (a SERIAL GENERATED ALWAYS AS (1) STORED)", "42601"),
        ("CREATE TABLE t (a INTEGER GENERATED ALWAYS AS IDENTITY GENERATED ALWAYS AS (1) STORED)", "42601"),
        ("CREATE TABLE t (a INTEGER GENERATED ALWAYS AS (1) STORED GENERATED ALWAYS AS IDENTITY)", "42601"),
        ("CREATE TABLE t (a VECTOR(2) GENERATED ALWAYS AS (1) STORED)", "0A000"),
        ("CREATE TABLE t (x INTEGER, a INTEGER GENERATED ALWAYS AS ((SELECT 1)) STORED)", "42P17"),
        ("CREATE TABLE t (x INTEGER, a INTEGER GENERATED ALWAYS AS (count(x)) STORED)", "42P17"),
        ("CREATE TABLE t (x INTEGER, a INTEGER GENERATED ALWAYS AS (sum(x) OVER ()) STORED)", "42P17"),
        ("CREATE TABLE t (x INTEGER, a INTEGER GENERATED ALWAYS AS (unnest(x)) STORED)", "42P17"),
        ("CREATE TABLE t (a TIMESTAMPTZ GENERATED ALWAYS AS (now()) STORED)", "42P17"),
        ("CREATE TABLE t (a DOUBLE PRECISION GENERATED ALWAYS AS (random()) STORED)", "42P17"),
        ("CREATE TABLE t (a DATE GENERATED ALWAYS AS (CURRENT_DATE) STORED)", "42P17"),
        ("CREATE TABLE t (x INTEGER, a INTEGER GENERATED ALWAYS AS (my_udf(x)) STORED)", "42P17"),
        ("CREATE TABLE t (x INTEGER, a INTEGER GENERATED ALWAYS AS (x IS DISTINCT FROM 1) STORED)", "42601"),
        (
            "CREATE TABLE t (x INTEGER, a INTEGER GENERATED ALWAYS AS (x) STORED REFERENCES p (k) ON UPDATE CASCADE)",
            "42601",
        ),
        (
            "CREATE TABLE t (x INTEGER, a INTEGER GENERATED ALWAYS AS (x) STORED, FOREIGN KEY (a) REFERENCES p (k) ON DELETE SET NULL)",
            "42601",
        ),
    ] {
        assert_eq!(parse(sql).err().as_deref(), Some(code), "{sql}");
    }
    // `ON DELETE CASCADE`・NO ACTION は生成列の参照元でも受理する。
    parse_ok("CREATE TABLE t (x INTEGER, a INTEGER GENERATED ALWAYS AS (x) STORED REFERENCES p (k) ON DELETE CASCADE)");
    parse_ok(
        "CREATE TABLE t (x INTEGER, a INTEGER GENERATED ALWAYS AS (x) STORED REFERENCES p (k))",
    );
    // 生成列を参照元に含まない FK は参照アクションを自由に使える。
    parse_ok("CREATE TABLE t (x INTEGER REFERENCES p (k) ON UPDATE CASCADE, a INTEGER GENERATED ALWAYS AS (x) STORED)");
}

/// NoSQL 表層の表作成（従来方式の行識別）は生成列を持てない（TABLE-50 (5)）。
#[test]
// intentional: docs/design/generated-column.md
fn legacy_row_identity_surface_rejects_generated_columns() {
    let tokens = tokenize("CREATE TABLE t (a INTEGER, b INTEGER GENERATED ALWAYS AS (a) STORED)")
        .expect("tokenize");
    let err = validate_create_table_tokens_with_implicit_id(&tokens).expect_err("rejected");
    assert_eq!(err.wire_code(), "0A000");
}

