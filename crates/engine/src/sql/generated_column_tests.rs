#[test]
fn binding_stage_attaches_canonical_expression_and_references() {
    let schema = build_ok(
        "CREATE TABLE t (g INTEGER GENERATED ALWAYS AS ((b + a) * 2) STORED, a INTEGER, b INTEGER, c TEXT)",
    );
    let g = &schema.columns[0];
    let def = g.generated.as_ref().expect("generated");
    // 参照列は宣言順・重複なし（前方参照を許す）。
    assert_eq!(def.referenced_columns, ["a", "b"]);
    assert!(def.expression.contains('a') && def.expression.contains('b'));
    assert!(def.expression.len() <= crate::catalog::MAX_GENERATED_EXPRESSION_SQL_LEN);
    // 描画は再解析で同じ描画に戻る（往復一致）。
    let reparsed =
        crate::sql::allowlist::parse_generated_expression_text(&def.expression).expect("reparse");
    assert_eq!(
        crate::sql::check_constraint::render_expr(&reparsed),
        def.expression
    );
    // 他の列は生成列ではない。
    assert!(schema.columns.iter().skip(1).all(|c| !c.is_generated()));
}

#[test]
// intentional: docs/design/generated-column.md
fn binding_stage_sqlstate_table() {
    for (sql, code) in [
        ("CREATE TABLE t (a INTEGER, b INTEGER GENERATED ALWAYS AS (zzz) STORED)", "42703"),
        ("CREATE TABLE t (b INTEGER GENERATED ALWAYS AS (b + 1) STORED)", "42P17"),
        (
            "CREATE TABLE t (a INTEGER, b INTEGER GENERATED ALWAYS AS (a) STORED, c INTEGER GENERATED ALWAYS AS (b) STORED)",
            "42P17",
        ),
        ("CREATE TABLE t (a INTEGER, b TEXT GENERATED ALWAYS AS (a) STORED)", "42804"),
        ("CREATE TABLE t (a TEXT, b INTEGER GENERATED ALWAYS AS (a) STORED)", "42804"),
        ("CREATE TABLE t (a TEXT, b TEXT GENERATED ALWAYS AS (a COLLATE \"C\") STORED)", "0A000"),
        ("CREATE TABLE t (a INTEGER, b NUMERIC(10, 2) GENERATED ALWAYS AS (a) STORED)", "0A000"),
        ("CREATE TABLE t (a INTEGER, b JSON GENERATED ALWAYS AS (a) STORED)", "0A000"),
        ("CREATE TABLE t (v VECTOR(2), b INTEGER GENERATED ALWAYS AS (v) STORED)", "0A000"),
        // 型依存の非決定性（TIMESTAMPTZ を含む CAST）は束縛段で 42P17。
        (
            "CREATE TABLE t (a TEXT, b TEXT GENERATED ALWAYS AS (CAST(CAST(a AS TIMESTAMPTZ) AS TEXT)) STORED)",
            "42P17",
        ),
    ] {
        assert_eq!(build(sql).err().as_deref(), Some(code), "{sql}");
    }
}

/// 式の長さ超過は確保より前に `54000`（正規描画が上限を超える）。
#[test]
fn binding_stage_rejects_too_long_expression() {
    let long = (0..600)
        .map(|_| "'abcdefgh'")
        .collect::<Vec<_>>()
        .join(" || ");
    let sql = format!("CREATE TABLE t (a INTEGER, b TEXT GENERATED ALWAYS AS ({long}) STORED)");
    assert_eq!(build(&sql).err().as_deref(), Some("54000"));
}

/// 参照列数の上限（32）を超える式は `54000`。
#[test]
fn binding_stage_rejects_too_many_referenced_columns() {
    let n = crate::catalog::MAX_GENERATED_REFERENCED_COLUMNS + 1;
    let cols: Vec<String> = (0..n).map(|i| format!("c{i} INTEGER")).collect();
    let sum: Vec<String> = (0..n).map(|i| format!("c{i}")).collect();
    let sql = format!(
        "CREATE TABLE t ({}, g BIGINT GENERATED ALWAYS AS ({}) STORED)",
        cols.join(", "),
        sum.join(" + ")
    );
    assert_eq!(build(&sql).err().as_deref(), Some("54000"));
}

#[test]
fn keyword_literal_generated_expressions_are_accepted_and_roundtrip() {
    for sql in [
        "CREATE TABLE t (g BOOLEAN GENERATED ALWAYS AS (TRUE) STORED)",
        "CREATE TABLE t (g BOOLEAN GENERATED ALWAYS AS (FALSE) STORED)",
        "CREATE TABLE t (g INTEGER GENERATED ALWAYS AS (NULL) STORED)",
        "CREATE TABLE t (a INTEGER, g INTEGER GENERATED ALWAYS AS (COALESCE(a, NULL)) STORED)",
    ] {
        let schema = build_ok(sql);
        let def = schema
            .columns
            .iter()
            .find_map(|c| c.generated.as_ref())
            .expect("generated");
        let reparsed = crate::sql::allowlist::parse_generated_expression_text(&def.expression)
            .expect("reparse");
        assert_eq!(
            crate::sql::check_constraint::render_expr(&reparsed),
            def.expression,
            "{sql}"
        );
    }
}
