#[test]
fn schema_ddl_round_trips_to_an_identical_dump() {
    let p1 = unique_db_path("dump-rt-src");
    let _g1 = CleanupGuard(p1.clone());
    let p2 = unique_db_path("dump-rt-dst");
    let _g2 = CleanupGuard(p2.clone());
    let src = open_core(&p1);
    populate(&src, "tenant-a");
    let scope = SchemaDdlScope::shared_and_tenant("tenant-a");
    let first = dump(&src, &scope).expect("dump");
    let dst = open_core(&p2);
    replay(&dst, "tenant-a", &first);
    let second = dump(&dst, &scope).expect("dump again");
    assert_eq!(first, second);
}

/// 往復して同一の DDL 列になることを確かめる共通処理（元の DDL 列を返す）。
fn assert_round_trip(label: &str, tenant: &str, setup: &[&str]) -> Vec<(DdlSection, String)> {
    let p1 = unique_db_path(&format!("dump-{label}-src"));
    let _g1 = CleanupGuard(p1.clone());
    let p2 = unique_db_path(&format!("dump-{label}-dst"));
    let _g2 = CleanupGuard(p2.clone());
    let src = open_core(&p1);
    for sql in setup {
        ok(&src, tenant, sql);
    }
    let scope = SchemaDdlScope::shared_and_tenant(tenant);
    let first = dump(&src, &scope).expect("dump");
    let dst = open_core(&p2);
    replay(&dst, tenant, &first);
    let second = dump(&dst, &scope).expect("dump again");
    assert_eq!(first, second, "re-dump must match the original dump");
    first
}

