#[test]
fn pre_data_precedes_post_data_and_shared_only_has_no_tenant_objects() {
    let p1 = unique_db_path("dump-sections");
    let _g1 = CleanupGuard(p1.clone());
    let src = open_core(&p1);
    populate(&src, "tenant-a");
    let all = dump(&src, &SchemaDdlScope::shared_and_tenant("tenant-a")).expect("dump");
    let first_post = all
        .iter()
        .position(|(s, _)| *s == DdlSection::PostData)
        .expect("has post data");
    assert!(all[..first_post]
        .iter()
        .all(|(s, _)| *s == DdlSection::PreData));
    assert!(all[first_post..]
        .iter()
        .all(|(s, _)| *s == DdlSection::PostData));
    let shared = dump(&src, &SchemaDdlScope::shared_only()).expect("shared dump");
    let text: String = shared
        .iter()
        .map(|(_, s)| s.as_str())
        .collect::<Vec<_>>()
        .join("\n");
    for tenant_only in [
        "SCHEMA", "ROLE", "FUNCTION", "TRIGGER", "POLICY", "setval", "app.",
    ] {
        assert!(
            !text.contains(tenant_only),
            "{tenant_only} must not be in a shared-only dump"
        );
    }
    assert!(text.contains("CREATE TABLE \"parent\""));
}

#[test]
fn other_tenants_objects_never_appear_in_a_tenants_dump() {
    let p1 = unique_db_path("dump-tenants");
    let _g1 = CleanupGuard(p1.clone());
    let src = open_core(&p1);
    ok(
        &src,
        "tenant-a",
        "CREATE TABLE shared_t (id BIGINT PRIMARY KEY, v TEXT)",
    );
    ok(&src, "tenant-a", "CREATE SCHEMA a_only");
    ok(&src, "tenant-a", "CREATE TABLE a_only.at1 (x INTEGER)");
    ok(
        &src,
        "tenant-a",
        "CREATE ROLE role_of_a LOGIN PASSWORD 'pw'",
    );
    ok(&src, "tenant-b", "CREATE SCHEMA b_secret");
    ok(&src, "tenant-b", "CREATE TABLE b_secret.bt1 (x INTEGER)");
    ok(
        &src,
        "tenant-b",
        "CREATE VIEW b_secret.bv AS SELECT x FROM b_secret.bt1",
    );
    ok(
        &src,
        "tenant-b",
        "CREATE ROLE role_of_b LOGIN PASSWORD 'pw'",
    );
    ok(
        &src,
        "tenant-b",
        "CREATE FUNCTION fn_of_b(x INTEGER) RETURNS INTEGER LANGUAGE sql AS $q$ SELECT x $q$",
    );
    ok(
        &src,
        "tenant-b",
        "CREATE POLICY pol_of_b ON shared_t USING (id > 0)",
    );
    ok(
        &src,
        "tenant-b",
        "ALTER TABLE shared_t ENABLE ROW LEVEL SECURITY",
    );
    let a = dump(&src, &SchemaDdlScope::shared_and_tenant("tenant-a")).expect("dump a");
    let text: String = a
        .iter()
        .map(|(_, s)| s.as_str())
        .collect::<Vec<_>>()
        .join("\n");
    for secret in [
        "b_secret",
        "bt1",
        "role_of_b",
        "fn_of_b",
        "pol_of_b",
        "ROW LEVEL SECURITY",
    ] {
        assert!(!text.contains(secret), "{secret} leaked into tenant-a dump");
    }
    assert!(text.contains("a_only") && text.contains("role_of_a"));
    let b = dump(&src, &SchemaDdlScope::shared_and_tenant("tenant-b")).expect("dump b");
    let text_b: String = b
        .iter()
        .map(|(_, s)| s.as_str())
        .collect::<Vec<_>>()
        .join("\n");
    for secret in ["a_only", "at1", "role_of_a"] {
        assert!(
            !text_b.contains(secret),
            "{secret} leaked into tenant-b dump"
        );
    }
    assert!(text_b.contains("b_secret") && text_b.contains("pol_of_b"));
    // 他テナントしか SCHEMA を持たない状況でも、テナントを持たない共有分の書き出しは成功する。
    dump(&src, &SchemaDdlScope::shared_only()).expect("shared dump");
}

#[test]
fn table_with_implicit_id_row_identity_fails_the_whole_dump() {
    use engine::catalog::{ColumnDef, ColumnType, TableSchema};
    let p1 = unique_db_path("dump-legacy");
    let _g1 = CleanupGuard(p1.clone());
    let storage = Storage::open(&p1).expect("open");
    storage
        .create_table(&TableSchema::new(
            "legacy_docs",
            vec![ColumnDef::new("body", ColumnType::Text, true)],
        ))
        .expect("create legacy table");
    let mut seen = 0u32;
    let err = storage
        .export_schema_ddl(&SchemaDdlScope::shared_only(), |_| {
            seen += 1;
            Ok::<(), std::convert::Infallible>(())
        })
        .expect_err("legacy row identity cannot be written as SQL");
    match err {
        SchemaDdlError::Unsupported(u) => {
            assert_eq!(u.kind, "table");
            // 固定文言で、表名を含めない。
            assert!(!u.reason.contains("legacy_docs"));
        }
        other => panic!("expected Unsupported, got {other:?}"),
    }
}

