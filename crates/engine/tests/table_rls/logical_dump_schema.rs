#[test]
fn output_order_does_not_depend_on_internal_schema_ids() {
    // SCHEMA を名前の逆順に作ると内部 ID が名前順と逆になる。復元先では名前順に ID が付き直されるため、
    // 出力順を内部キーの順で決めると 2 回目のダンプと食い違う。
    let dump = assert_round_trip(
        "order",
        "tenant-a",
        &[
            "CREATE SCHEMA zz",
            "CREATE SCHEMA aa",
            "CREATE TABLE zz.t (a INTEGER PRIMARY KEY, b TEXT)",
            "CREATE TABLE aa.t (a INTEGER PRIMARY KEY, b TEXT)",
            "CREATE TABLE plain_t (a INTEGER PRIMARY KEY, b TEXT)",
            "CREATE VIEW zz.v AS SELECT b FROM zz.t",
            "CREATE VIEW aa.v AS SELECT b FROM aa.t",
            "CREATE INDEX ix ON zz.t (b)",
            "CREATE INDEX ix ON aa.t (b)",
            "CREATE FUNCTION zz.f(x INTEGER) RETURNS INTEGER LANGUAGE sql AS $q$ SELECT x $q$",
            "CREATE FUNCTION aa.f(x INTEGER) RETURNS INTEGER LANGUAGE sql AS $q$ SELECT x $q$",
            "CREATE FUNCTION trg() RETURNS trigger LANGUAGE plpgsql AS $q$ BEGIN RETURN NEW; END $q$",
            "CREATE TRIGGER tg AFTER INSERT ON zz.t FOR EACH ROW EXECUTE FUNCTION trg()",
            "CREATE TRIGGER tg AFTER INSERT ON aa.t FOR EACH ROW EXECUTE FUNCTION trg()",
            "CREATE POLICY pp ON zz.t USING (a > 0)",
            "CREATE POLICY pp ON aa.t USING (a > 0)",
            "ALTER TABLE zz.t ENABLE ROW LEVEL SECURITY",
            "ALTER TABLE aa.t ENABLE ROW LEVEL SECURITY",
        ],
    );
    let tables: Vec<&str> = dump
        .iter()
        .filter(|(_, s)| s.starts_with("CREATE TABLE"))
        .map(|(_, s)| s.as_str())
        .collect();
    // 共有の表が先、SCHEMA 配下は SCHEMA 名の昇順。
    assert!(tables[0].starts_with("CREATE TABLE \"plain_t\""));
    assert!(tables[1].starts_with("CREATE TABLE aa.t"));
    assert!(tables[2].starts_with("CREATE TABLE zz.t"));
}

#[test]
fn role_password_verifier_survives_the_round_trip_unchanged() {
    // 復元側の CREATE ROLE ... PASSWORD は、事前ハッシュ済みの検証子をそのまま保存し、平文として
    // 再ハッシュしない（再ハッシュすると salt が変わり、元のパスワードで認証できなくなる）。
    let verifier = |core: &EngineCore| {
        let ident = EngineCore::login_identifier("tenant-a", "app").expect("identifier");
        core.resolve_login_role(&ident)
            .expect("lookup")
            .map(|c| c.scram_verifier.clone())
            .expect("role exists")
    };
    let p1 = unique_db_path("dump-verifier-src");
    let _g1 = CleanupGuard(p1.clone());
    let p2 = unique_db_path("dump-verifier-dst");
    let _g2 = CleanupGuard(p2.clone());
    let src = open_core(&p1);
    ok(
        &src,
        "tenant-a",
        "CREATE ROLE app LOGIN PASSWORD 'plain-secret'",
    );
    let stmts = dump(&src, &SchemaDdlScope::tenant_only("tenant-a")).expect("dump");
    let text: String = stmts.iter().map(|(_, s)| s.as_str()).collect();
    assert!(text.contains("SCRAM-SHA-256$") && !text.contains("plain-secret"));
    let dst = open_core(&p2);
    replay(&dst, "tenant-a", &stmts);
    assert_eq!(verifier(&src), verifier(&dst));
}

#[test]
fn views_are_ordered_by_every_relation_their_body_reads() {
    // 名前順と依存順が逆になるよう、依存先を後ろの名前にする。集合演算の後続の枝で別の VIEW を読む
    // VIEW は、`base_relation`（先頭の枝）だけを見る並べ方では依存先より先に出てしまう。
    // （この SQL 表層は JOIN・部分問い合わせ・CTE の本文で別の VIEW を読む VIEW を作らせない。
    // それらの参照も同じ `view_body_relations` が集めるため、並べ方は同じ導出に従う。）
    let dump = assert_round_trip(
        "view-order",
        "tenant-a",
        &[
            "CREATE TABLE docs (id BIGINT PRIMARY KEY, x TEXT)",
            "CREATE TABLE notes (id BIGINT PRIMARY KEY, y TEXT)",
            "CREATE VIEW z_base AS SELECT id FROM docs",
            "CREATE VIEW z_base2 AS SELECT id FROM notes",
            "CREATE VIEW a_union AS SELECT id FROM docs UNION ALL SELECT id FROM z_base",
            "CREATE VIEW b_inter AS SELECT id FROM docs INTERSECT SELECT id FROM z_base2",
            "CREATE VIEW c_except AS SELECT id FROM docs EXCEPT SELECT id FROM z_base2",
            "CREATE VIEW d_two AS SELECT id FROM docs UNION SELECT id FROM z_base \
             UNION SELECT id FROM z_base2",
        ],
    );
    let pos = |name: &str| {
        dump.iter()
            .position(|(_, s)| s.starts_with(&format!("CREATE VIEW \"{name}\"")))
            .unwrap_or_else(|| panic!("{name} missing"))
    };
    assert!(pos("z_base") < pos("a_union"));
    assert!(pos("z_base2") < pos("b_inter"));
    assert!(pos("z_base2") < pos("c_except"));
    assert!(pos("z_base") < pos("d_two") && pos("z_base2") < pos("d_two"));
}
