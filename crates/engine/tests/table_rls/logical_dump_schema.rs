//! スキーマの DDL 書き出し（論理ダンプの DDL 側。RECOVER-16・Issue #2160。ポインタ:
//! `docs/spec/04-behavior/recovery.md` の RECOVER-16、設計メモ: `docs/design/logical-dump.md`）の結合テスト。
//!
//! 検査する契約:
//! 1. 多様なオブジェクトを作った DB から書き出した DDL を空 DB で再実行し、再度書き出した DDL の列が
//!    元と一致する（往復で同一カタログ）
//! 2. 書き出せないオブジェクト（暗黙 id の表）があればダンプ全体が失敗する（fail-closed）
//! 3. 他テナントのオブジェクトは出力にもエラーにも現れない
//! 4. ロール・権限（所有者・付与者・ACL・既定権限・メンバーシップ・初期権限）も指示文として往復し、
//!    他テナントの分は混ざらない（Issue #3096）

use engine::catalog::ddl_export::{DdlSection, SchemaDdlError, SchemaDdlScope};
use engine::core::{BootstrapUser, EngineCore, UsersFileRoleBinding};
use engine::kernel::CpuScalarProvider;
use engine::policy::PolicyContext;
use engine::sql::allowlist::SqlSurfaceError;
use engine::sql::mode::SessionState;
use engine::sql::SqlOutcome;
use engine::storage::{Storage, Visibility};

use crate::temp_db;
use temp_db::{unique_db_path, CleanupGuard};

fn ctx(tenant: &str) -> PolicyContext {
    PolicyContext::with_visibilities(tenant, [Visibility::Public, Visibility::Private])
        .expect("valid tenant")
}

fn open_core(path: &std::path::Path) -> EngineCore {
    EngineCore::from_storage(
        Storage::open(path).expect("open storage"),
        Box::new(CpuScalarProvider),
    )
}

fn run(core: &EngineCore, tenant: &str, sql: &str) -> Result<SqlOutcome, SqlSurfaceError> {
    let mut session = SessionState::default();
    session.allow_ddl();
    core.execute_sql_in_session(&ctx(tenant), &mut session, sql)
}

fn ok(core: &EngineCore, tenant: &str, sql: &str) {
    run(core, tenant, sql).unwrap_or_else(|e| panic!("{sql} must succeed: {e}"));
}

/// 範囲の DDL を（区分, 文）の列として集める。
fn dump(
    core: &EngineCore,
    scope: &SchemaDdlScope,
) -> Result<Vec<(DdlSection, String)>, SchemaDdlError<std::convert::Infallible>> {
    let mut out = Vec::new();
    core.export_schema_ddl(scope, |st| {
        out.push((st.section, st.sql.to_string()));
        Ok::<(), std::convert::Infallible>(())
    })?;
    Ok(out)
}

fn replay(core: &EngineCore, tenant: &str, stmts: &[(DdlSection, String)]) {
    for (_, sql) in stmts {
        if sql.starts_with("RESTORE ") {
            // ロール・権限の復元指示は SQL ではなく engine の復元用入口で適用する（Issue #3096）。
            core.apply_restore_directive(tenant, sql)
                .unwrap_or_else(|e| panic!("restore directive must apply: {e}"));
        } else {
            ok(core, tenant, sql);
        }
    }
}

