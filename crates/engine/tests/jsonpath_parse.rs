#[test]
fn ast_shapes() {
    // `<>` は `!=` と同じ意味。
    assert_eq!(ok("$ <> 1").expr, ok("$ != 1").expr);
    // 乗算が加算より強い。
    match ok("$.a + $.b * 2").expr {
        PathNode::Arith {
            op: ArithOp::Add,
            rhs,
            ..
        } => assert!(matches!(
            *rhs,
            PathNode::Arith {
                op: ArithOp::Mul,
                ..
            }
        )),
        other => panic!("{other:?}"),
    }
    // `1.2.a` は (1.2)."a"。
    match ok("1.2.a").expr {
        PathNode::Path { base, ops } => {
            assert!(is_num(&base, "1.2"));
            assert_eq!(ops, vec![member("a")]);
        }
        other => panic!("{other:?}"),
    }
    // 述語の後ろにアクセサを続けられる。
    match ok("(1 == 1).type()").expr {
        PathNode::Path { base, ops } => {
            assert!(matches!(*base, PathNode::Compare { .. }));
            assert_eq!(ops, vec![AccessorOp::Method(Method::Type)]);
        }
        other => panic!("{other:?}"),
    }
    // フィルタは連続でき、連鎖は平坦な ops になる。
    match ok("$.a ? (@ > 1) ? (@ < 5)").expr {
        PathNode::Path { ops, .. } => {
            assert_eq!(ops.len(), 3);
            assert!(matches!(ops[1], AccessorOp::Filter(_)));
            assert!(matches!(ops[2], AccessorOp::Filter(_)));
        }
        other => panic!("{other:?}"),
    }
    match ok("$.**{2 to last}").expr {
        PathNode::Path { ops, .. } => assert_eq!(
            ops,
            vec![AccessorOp::AnyPath {
                from: AnyLevel::Level(2),
                to: AnyLevel::Last
            }]
        ),
        other => panic!("{other:?}"),
    }
    match ok("$.**").expr {
        PathNode::Path { ops, .. } => assert_eq!(
            ops,
            vec![AccessorOp::AnyPath {
                from: AnyLevel::Level(0),
                to: AnyLevel::Last
            }]
        ),
        other => panic!("{other:?}"),
    }
    match ok("$[1 to 2, last]").expr {
        PathNode::Path { ops, .. } => match &ops[0] {
            AccessorOp::Subscripts(items) => {
                assert_eq!(items.len(), 2);
                assert!(items[0].to.is_some());
                assert_eq!(items[1].from, PathNode::Last);
            }
            other => panic!("{other:?}"),
        },
        other => panic!("{other:?}"),
    }
}

#[test]
fn variables_keys_and_numbers() {
    assert_eq!(ok("$x").expr, PathNode::Variable("x".into()));
    assert_eq!(ok("$1").expr, PathNode::Variable("1".into()));
    assert_eq!(ok("$\"x y\"").expr, PathNode::Variable("x y".into()));
    // 引用符なしのキーでも `\u` エスケープが効く。
    assert_eq!(ok(r"$.\u0041"), ok("$.A"));
    assert_eq!(
        ok(r#"$."a\tb""#).expr,
        PathNode::Path {
            base: Box::new(PathNode::Root),
            ops: vec![member("a\tb")]
        }
    );
    assert!(is_num(&ok("0x1F").expr, "31"));
    assert!(is_num(&ok("1_000.5").expr, "1000.5"));
    assert!(is_num(&ok(".1").expr, "0.1"));
    assert!(is_num(&ok("1.e3").expr, "1e3"));
    assert!(is_num(&ok("1e400").expr, "1e400"));
}

#[test]
fn limits_are_inclusive_and_fail_closed() {
    // 入力長。
    let at_limit = format!("${}", " ".repeat(MAX_JSONPATH_INPUT_LEN - 1));
    assert!(parse_jsonpath(&at_limit).is_ok());
    let over = format!("${}", " ".repeat(MAX_JSONPATH_INPUT_LEN));
    let err = parse_jsonpath(&over).unwrap_err();
    assert_eq!(err, JsonPathParseError::TooLong);
    assert_eq!(err.wire_code(), "54000");

    // 括弧の入れ子深さ。
    let parens = |n: usize| format!("{}1{}", "(".repeat(n), ")".repeat(n));
    assert!(parse_jsonpath(&parens(MAX_JSONPATH_NESTING_DEPTH)).is_ok());
    assert_eq!(
        parse_jsonpath(&parens(MAX_JSONPATH_NESTING_DEPTH + 1)).unwrap_err(),
        JsonPathParseError::TooDeep
    );
    // 単項演算子の連続。
    let unary = |n: usize| format!("{}1", "-".repeat(n));
    assert!(parse_jsonpath(&unary(MAX_JSONPATH_NESTING_DEPTH)).is_ok());
    assert_eq!(
        parse_jsonpath(&unary(MAX_JSONPATH_NESTING_DEPTH + 1)).unwrap_err(),
        JsonPathParseError::TooDeep
    );
    // フィルタの入れ子（1 段あたり filter と exists の 2 回入る）。
    let nested = |n: usize| {
        let mut s = String::from("$");
        for _ in 0..n {
            s.push_str(" ? (exists(@");
        }
        for _ in 0..n {
            s.push_str("))");
        }
        s
    };
    assert!(parse_jsonpath(&nested(MAX_JSONPATH_NESTING_DEPTH / 2)).is_ok());
    assert_eq!(
        parse_jsonpath(&nested(MAX_JSONPATH_NESTING_DEPTH / 2 + 1)).unwrap_err(),
        JsonPathParseError::TooDeep
    );

    // 数値リテラル長（10 進・基数つき）。
    let lit = "1".repeat(MAX_JSONPATH_NUMERIC_LITERAL_LEN);
    assert!(parse_jsonpath(&lit).is_ok());
    assert_eq!(
        parse_jsonpath(&format!("{lit}1")).unwrap_err(),
        JsonPathParseError::LiteralTooLong
    );
    let hex_ok = format!("0x{}", "F".repeat(MAX_JSONPATH_NUMERIC_LITERAL_LEN - 2));
    assert!(parse_jsonpath(&hex_ok).is_ok());
    assert_eq!(
        parse_jsonpath(&format!("{hex_ok}F")).unwrap_err(),
        JsonPathParseError::LiteralTooLong
    );

    // 左結合の連鎖が作る式木の高さ。
    let chain = |k: usize| format!("1{}", "+1".repeat(k));
    assert!(parse_jsonpath(&chain(MAX_JSONPATH_NODE_HEIGHT - 1)).is_ok());
    assert_eq!(
        parse_jsonpath(&chain(MAX_JSONPATH_NODE_HEIGHT)).unwrap_err(),
        JsonPathParseError::TooDeep
    );
}

#[test]
fn long_accessor_chain_is_flat_and_droppable() {
    // 連続アクセサは平坦な `ops` に畳まれ、再帰的な drop でスタックを使い切らない。
    let path = format!("${}", ".a".repeat(30_000));
    match ok(&path).expr {
        PathNode::Path { ops, .. } => assert_eq!(ops.len(), 30_000),
        other => panic!("{other:?}"),
    }
    let path = format!("${}", "[0]".repeat(20_000));
    assert!(parse_jsonpath(&path).is_ok());
}

