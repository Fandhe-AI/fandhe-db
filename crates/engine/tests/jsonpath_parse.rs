/// PostgreSQL 17 との意図的な差分（入力, 本リポジトリの結果）。`like_regex` を含む入力は
/// 別規則（`expected`）で一括して扱う。
const DIVERGENCES: &[(&str, &str)] = &[
    // `\u0000`・`\x00`: PostgreSQL は 22P05。対応する ErrorClass が未追加のため暫定で 22P02。
    (r####""\x00""####, "22P02"),
    (r####""\u0000""####, "22P02"),
    (r####"$"\u0000""####, "22P02"),
    (r####""\u{0}""####, "22P02"),
    // 識別子の直後の `/*`: PostgreSQL は識別子の文字列を黙って捨てて受理／拒否が不定になる
    // 癖がある。本リポジトリは fail-closed で一律 42601 とする。
    (r####"last/* c */ $"####, "42601"),
    (r####"a/* c */ $"####, "42601"),
    (r####"last/**/$"####, "42601"),
    (r####"lax/* c */ $"####, "42601"),
    (r####"lax/**/$"####, "42601"),
    (r####"$.a/* */ b"####, "42601"),
];

/// 期待値。`like_regex` を含む入力で PostgreSQL が構文を受理（`OK`）または正規表現を
/// 拒否（`2201B`）する場合、本リポジトリは正規表現の依存が未承認のため一律 `0A000`。
fn expected(input: &str, pg: &'static str) -> &'static str {
    if let Some((_, w)) = DIVERGENCES.iter().find(|(i, _)| *i == input) {
        return w;
    }
    if input.contains("like_regex \"") && (pg == "OK" || pg == "2201B") {
        return "0A000";
    }
    pg
}

fn outcome(input: &str) -> String {
    match parse_jsonpath(input) {
        Ok(_) => "OK".to_string(),
        Err(e) => e.wire_code().to_string(),
    }
}

#[test]
fn matches_pg17_acceptance_and_sqlstate() {
    let mut bad = Vec::new();
    for (input, pg) in PG17_TABLE {
        let want = expected(input, pg);
        let got = outcome(input);
        if got != want {
            bad.push(format!("{input:?}: pg={pg} want={want} got={got}"));
        }
    }
    assert!(bad.is_empty(), "mismatches:\n{}", bad.join("\n"));
}

fn ok(input: &str) -> SqlJsonPath {
    parse_jsonpath(input).unwrap_or_else(|e| panic!("{input:?} should parse: {e:?}"))
}

